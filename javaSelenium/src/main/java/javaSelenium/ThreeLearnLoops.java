package javaSelenium;

import java.util.Iterator;

public class ThreeLearnLoops {

	public static void main(String[] args) {
		
		int num = 10;
		// for loop - Increment Operator
		
		for (int i = 0; i < num; i++) {
			System.out.println(i);
			
		}
		
System.out.println("***************************************************************************"); 

		// for loop - Decrement Operator
		
		for (int i = num; i>=0; i--) {
			
			System.out.println(i);
			
		}

	}

}
